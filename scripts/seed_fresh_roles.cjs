async function seedRoles() {
  try {
    await mongoose.connect(uri);
    console.log('Connected to MongoDB Atlas...');
    const db = mongoose.connection.db;

    const admin = await db.collection('employees').findOne({ role: 'admin' });
    const ownerId = admin ? String(admin._id) : 'admin-owner';

    const rolesCol = db.collection('workspaceroles');
    await rolesCol.deleteMany({});
    console.log('Cleared existing workspace roles in DB.');

    const docs = FRESH_ROLES.map(r => ({
      ...r,
      id: r.roleId,
      ownerId,
      createdAt: new Date(),
      updatedAt: new Date(),
    }));

    const result = await rolesCol.insertMany(docs);
    console.log(`Successfully inserted ${result.insertedCount} fresh corporate roles into MongoDB:`);
    docs.forEach(d => console.log(`- [${d.badge}] ${d.name} (${d.roleId})`));

  } catch (err) {
    console.error('Error seeding roles:', err);
    process.exit(1);
  } finally {
    await mongoose.disconnect();
  }
}

seedRoles();

