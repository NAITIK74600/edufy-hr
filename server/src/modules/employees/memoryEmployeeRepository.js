let records = [...DEFAULT_EMPLOYEES.map((e) => ({ ...e, save: async function() { return this } }))]
let audit = []

export function createMemoryEmployeeRepository() {
  return {
    async list({ page = 1, limit = 20, sort = 'name', direction = 'asc', search, ...filters } = {}) {
      let filtered = [...records]
      if (search) {
        const q = String(search).toLowerCase()
        filtered = filtered.filter((e) =>
          `${e.name} ${e.email} ${e.employeeId} ${e.department} ${e.designation}`.toLowerCase().includes(q)
        )
      }
      for (const field of ['department', 'designation', 'status', 'managerId', 'campus', 'role']) {
        if (filters[field]) {
          filtered = filtered.filter((e) => e[field] === filters[field])
        }
      }
      if (filters.employmentType) {
        const type = String(filters.employmentType).toLowerCase()
        if (type === 'intern') {
          filtered = filtered.filter((e) =>
            String(e.employmentType || '').toLowerCase() === 'intern' ||
            String(e.role || '').toLowerCase().includes('intern') ||
            String(e.designation || '').toLowerCase().includes('intern')
          )
        } else if (type === 'full_time') {
          filtered = filtered.filter((e) =>
            String(e.employmentType || '').toLowerCase() !== 'intern' &&
            !String(e.role || '').toLowerCase().includes('intern') &&
            !String(e.designation || '').toLowerCase().includes('intern')
          )
        }
      }
      const safePage = Math.max(1, Number(page) || 1)
      const safeLimit = Math.min(100, Math.max(1, Number(limit) || 20))
      return {
        records: filtered.slice((safePage - 1) * safeLimit, safePage * safeLimit),
        meta: { page: safePage, limit: safeLimit, total: filtered.length },
      }
    },
    async findById(id) {
      return records.find((e) => e.id === id || e._id === id || e.employeeId === id) ?? null
    },
    async findForUpdate(id) {
      const found = records.find((e) => e.id === id || e._id === id || e.employeeId === id)
      if (found && !found.save) {
        found.save = async function() { return this }
      }
      return found ?? null
    },
    async findManager(id) {
      const managerRoles = [
        'admin', 'hr', 'manager', 'director', 'team_lead', 'team_leader',
        'vertical_head', 'managing_director', 'co_founder', 'revenue_growth_manager',
        'senior_manager', 'general_manager', 'assistant_general_manager', 'head_of_sales', 'head_of_marketing',
      ]
      return (
        records.find(
          (e) => (e.id === id || e._id === id || e.employeeId === id) &&
                 managerRoles.includes(e.role) &&
                 e.status !== 'inactive'
        ) ?? null
      )
    },
    async getNextEmployeeCode() {
      let maxNum = 21200
      for (const rec of records) {
        const str = String(rec.employeeId || '').trim()
        const m = str.match(/^ETS(\d+)$/i)
        if (m) {
          const n = parseInt(m[1], 10)
          if (n > maxNum) maxNum = n
        } else {
          const digits = str.match(/\d{4,}/g)
          if (digits) {
            for (const d of digits) {
              const n = parseInt(d, 10)
              if (n > maxNum) maxNum = n
            }
          }
        }
      }
      return `ETS${maxNum + 1}`
    },
    async create(data) {
      const record = {
        id: `employee-${records.length + 1}`,
        _id: `employee-${records.length + 1}`,
        status: 'active',
        ...data,
        save: async function() { return this },
      }
      records.push(record)
      return record
    },
    async save(employee) {
      const idx = records.findIndex((e) => e.id === employee.id || e._id === employee._id)
      if (idx !== -1) {
        records[idx] = { ...records[idx], ...employee, save: async function() { return this } }
      }
      return employee
    },
    async listAudit(id) {
      return audit.filter((entry) => entry.entityId === id)
    },
    async addAudit(event) {
      const entry = { id: `audit-${audit.length + 1}`, createdAt: new Date(), ...event }
      audit.push(entry)
      return entry
    },
  }
}
