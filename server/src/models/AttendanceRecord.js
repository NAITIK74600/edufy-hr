import mongoose from 'mongoose'

const attendanceRecordSchema = new mongoose.Schema({
  employeeId: { type: String, required: true, trim: true, uppercase: true, index: true },
  employeeName: { type: String, required: true, trim: true },
  userId: { type: mongoose.Schema.Types.ObjectId, ref: 'Employee' },
  date: { type: String, required: true, trim: true, index: true }, // YYYY-MM-DD
  checkIn: { type: String, trim: true },
  checkInAt: { type: Date },
  checkOut: { type: String, trim: true, default: null },
  checkOutAt: { type: Date },
  status: { type: String, enum: ['present', 'late', 'half-day', 'short-hours', 'early-logout', 'lop', 'absent', 'on-leave'], default: 'present' },
  isEarlyLogout: { type: Boolean, default: false },
  isLop: { type: Boolean, default: false },
  isDoubleLop: { type: Boolean, default: false },
  doubleLopStatus: { type: String, enum: ['none', 'pending_approval', 'approved', 'rejected'], default: 'none' },
  doubleLopApprovedBy: { type: String, default: null },
  doubleLopApprovedAt: { type: Date, default: null },
  doubleLopReason: { type: String, default: null },
  isLate: { type: Boolean, default: false },
  isHalfDay: { type: Boolean, default: false },
  lateCount: { type: Number, default: 0 },
  earlyLogoutCount: { type: Number, default: 0 },
  offCampusDurationMinutes: { type: Number, default: 0 },
  verifiedCampusMinutes: { type: Number, default: 0 },
  policyEvaluation: { type: mongoose.Schema.Types.Mixed, default: null },
  shift: { type: String, trim: true, default: null },
  shiftCode: { type: String, trim: true, default: null },
  isOnBreak: { type: Boolean, default: false },
  currentBreak: {
    type: { type: String, default: null }, // 'lunch', 'tea', 'other'
    startTime: { type: String, default: null },
    startAt: { type: Date, default: null },
  },
  breaks: [
    {
      type: { type: String, default: 'lunch' },
      startTime: { type: String },
      startAt: { type: Date },
      endTime: { type: String },
      endAt: { type: Date },
      durationMinutes: { type: Number, default: 0 },
    },
  ],
  totalBreakMinutes: { type: Number, default: 0 },
  wifiSSID: { type: String, trim: true, default: '' },
  bssid: { type: String, trim: true, default: '', uppercase: true },
  wifiVerified: { type: Boolean, default: false },
  clientIp: { type: String, trim: true, default: '' },
  ipVerified: { type: Boolean, default: false },
  latitude: { type: Number, default: null },
  longitude: { type: Number, default: null },
  accuracy: { type: Number, default: null },
  distanceMeters: { type: Number, default: null },
  gpsVerified: { type: Boolean, default: false },
  locationName: { type: String, trim: true, default: '' },
  verificationMethod: {
    type: String,
    enum: [
      'wifi_and_gps',
      'gps_geofence',
      'office_network',
      'wifi_trusted',
      'wifi_only',
      'wifi_metadata_only',
      'ip_verified',
      'remote',
    ],
    default: 'remote',
  },
  totalHours: { type: String, default: 'Active (Live)' },
  notes: { type: String, trim: true, default: '' },
  autoPunchOut: { type: Boolean, default: false },
  punchOutReason: { type: String, trim: true, default: '' },
  punchOutType: { type: String, trim: true, default: 'manual' }, // 'manual' | 'auto'
  lastConnectedAt: { type: Date, default: null },
  disconnectedSince: { type: Date, default: null },
  geofenceStatus: { type: String, enum: ['inside', 'outside', 'unknown', 'uncertain'], default: 'unknown' },
  punchInLocation: {
    latitude: { type: Number, default: null },
    longitude: { type: Number, default: null },
    accuracy: { type: Number, default: null },
    distanceMeters: { type: Number, default: null },
    geofenceStatus: { type: String, enum: ['inside', 'outside', 'unknown', 'uncertain'], default: 'unknown' },
    networkType: { type: String, default: 'unknown' },
    wifiSSID: { type: String, trim: true, default: '' },
    bssid: { type: String, trim: true, default: '' },
    clientIp: { type: String, trim: true, default: '' },
    wifiVerified: { type: Boolean, default: false },
    ipVerified: { type: Boolean, default: false },
    gpsVerified: { type: Boolean, default: false },
    locationName: { type: String, trim: true, default: '' },
    timestamp: { type: Date, default: null },
  },
  liveLocation: {
    latitude: { type: Number, default: null },
    longitude: { type: Number, default: null },
    accuracy: { type: Number, default: null },
    distanceMeters: { type: Number, default: null },
    geofenceStatus: { type: String, enum: ['inside', 'outside', 'unknown', 'uncertain'], default: 'unknown' },
    locationFreshness: { type: String, enum: ['live', 'recent', 'stale', 'offline', 'unavailable', 'uncertain'], default: 'unavailable' },
    locationPermission: { type: String, enum: ['granted', 'denied', 'prompt', 'unknown'], default: 'unknown' },
    connectivityStatus: { type: String, enum: ['online', 'offline'], default: 'online' },
    networkType: { type: String, default: 'unknown' },
    wifiSSID: { type: String, trim: true, default: '' },
    bssid: { type: String, trim: true, default: '' },
    clientIp: { type: String, trim: true, default: '' },
    wifiVerified: { type: Boolean, default: false },
    ipVerified: { type: Boolean, default: false },
    gpsVerified: { type: Boolean, default: false },
    locationSource: { type: String, default: 'unknown' },
    locationName: { type: String, trim: true, default: '' },
    deviceCapturedAt: { type: Date, default: null },
    serverReceivedAt: { type: Date, default: null },
    lastSyncAt: { type: Date, default: null },
  },
  geofenceExitAt: { type: Date, default: null },
  geofenceGraceExpiresAt: { type: Date, default: null, index: true },
  geofenceWarningSentAt: { type: Date, default: null },
  offlineDetectedAt: { type: Date, default: null },
  offlineGraceExpiresAt: { type: Date, default: null, index: true },
  offlineWarningSentAt: { type: Date, default: null },
  lastVerifiedLocationAt: { type: Date, default: null },
  lastVerifiedLatitude: { type: Number, default: null },
  lastVerifiedLongitude: { type: Number, default: null },
  lastVerifiedAccuracy: { type: Number, default: null },
  lastVerifiedLocationName: { type: String, trim: true, default: '' },
  autoPunchOutReasonCode: { type: String, trim: true, default: null },
  autoPunchOutPolicy: { type: String, trim: true, default: null },
  autoPunchOutExecutedAt: { type: Date, default: null },
  advanceWarningSentAt: { type: Date, default: null },
  reviewStatus: { type: String, enum: ['none', 'pending', 'confirmed', 'corrected'], default: 'none', index: true },
  reviewedBy: { type: String, default: null },
  reviewedAt: { type: Date, default: null },
  reviewRemarks: { type: String, default: null },
  correctionHistory: [
    {
      correctedBy: { type: String },
      correctedAt: { type: Date, default: Date.now },
      previousCheckOut: { type: String },
      newCheckOut: { type: String },
      reason: { type: String },
    },
  ],
  auditEvents: [
    {
      eventType: { type: String, required: true },
      eventTimestamp: { type: Date, default: Date.now },
      description: { type: String, default: '' },
      source: { type: String, default: 'system' }, // 'system' | 'device' | 'hr' | 'scheduler'
      metadata: { type: mongoose.Schema.Types.Mixed, default: {} },
    },
  ],
}, { timestamps: true, strict: true })

attendanceRecordSchema.index({ employeeId: 1, date: 1 }, { unique: true })
attendanceRecordSchema.index({ date: 1, status: 1 })
attendanceRecordSchema.index({ checkIn: 1, checkOut: 1, geofenceGraceExpiresAt: 1 })
attendanceRecordSchema.index({ checkIn: 1, checkOut: 1, offlineGraceExpiresAt: 1 })
attendanceRecordSchema.index({ checkIn: 1, checkOut: 1, date: 1 })
attendanceRecordSchema.index({ reviewStatus: 1, date: 1 })

export const AttendanceRecord = mongoose.models.AttendanceRecord ?? mongoose.model('AttendanceRecord', attendanceRecordSchema)
