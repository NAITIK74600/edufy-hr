import mongoose from 'mongoose'

const EVENT_CATEGORIES = [
  'Company Meeting',
  'Department Meeting',
  'Individual Meeting',
  'Client Meeting',
  'Employee Birthday',
  'Work Anniversary',
  'Company Holiday',
  'Training Session',
  'Interview',
  'Performance Review',
  'Project Deadline',
  'Employee Onboarding',
  'Contract Expiry',
  'Probation Completion',
  'Office Event',
  'Custom Event',
  // Backward compatibility aliases
  'Meeting',
  'Training',
  'Announcement',
  'Deadline',
  'Department',
  'Company',
  'Celebration',
  'Other',
]

const participantSchema = new mongoose.Schema({
  employeeId: { type: String, required: true, trim: true },
  name: { type: String, required: true, trim: true },
  email: { type: String, trim: true },
  department: { type: String, trim: true },
  avatarUrl: { type: String, default: null },
  role: { type: String, enum: ['organizer', 'required', 'optional'], default: 'required' },
  rsvpStatus: { type: String, enum: ['pending', 'accepted', 'declined', 'tentative'], default: 'pending' },
  respondedAt: { type: Date, default: null },
  responseNote: { type: String, trim: true, maxlength: 500, default: '' },
}, { _id: false })

const reminderItemSchema = new mongoose.Schema({
  minutesBefore: { type: Number, required: true, default: 15 },
  channel: { type: String, enum: ['in_app', 'email', 'both'], default: 'both' },
  sent: { type: Boolean, default: false },
  sentAt: { type: Date, default: null },
}, { _id: false })

const calendarEventSchema = new mongoose.Schema({
  title: { type: String, required: true, trim: true, maxlength: 250 },
  description: { type: String, trim: true, maxlength: 5000, default: '' },
  category: {
    type: String,
    enum: EVENT_CATEGORIES,
    default: 'Company Meeting',
  },
  date: { type: String, required: true, index: true }, // YYYY-MM-DD (Start Date)
  startDate: { type: String }, // YYYY-MM-DD
  endDate: { type: String }, // YYYY-MM-DD
  startTime: { type: String, default: null }, // e.g. "10:00"
  endTime: { type: String, default: null }, // e.g. "11:00"
  allDay: { type: Boolean, default: false },

  // Organizer details
  organizer: {
    employeeId: { type: String },
    name: { type: String },
    email: { type: String },
    department: { type: String },
    avatarUrl: { type: String, default: null },
  },
  ownerId: { type: String, ref: 'Employee', index: true },
  createdBy: { type: String },
  updatedBy: { type: String },

  // Participants & RSVPs
  participants: { type: [participantSchema], default: [] },

  // Department & Targeting
  department: { type: String, default: 'All', index: true },
  applicableDepartments: { type: [String], default: ['All'] },

  // Physical Location & Google Maps
  location: {
    name: { type: String, trim: true, default: 'Head Office / Online' },
    address: { type: String, trim: true, default: '' },
    formattedAddress: { type: String, trim: true, default: '' },
    latitude: { type: Number, default: null },
    longitude: { type: Number, default: null },
    placeId: { type: String, default: null },
    mapsUrl: { type: String, default: null },
    isPhysical: { type: Boolean, default: false },
  },

  // Online Meeting (Google Meet, Zoom, Teams, or Custom)
  meetingLink: {
    url: { type: String, trim: true, default: '' },
    provider: { type: String, enum: ['google_meet', 'zoom', 'teams', 'custom', 'none'], default: 'none' },
    googleEventId: { type: String, default: null },
    googleMeetCode: { type: String, default: null },
    conferenceId: { type: String, default: null },
    htmlLink: { type: String, default: null },
    autoGenerated: { type: Boolean, default: false },
  },

  priority: { type: String, enum: ['low', 'normal', 'high', 'urgent'], default: 'normal' },
  visibility: { type: String, enum: ['public', 'private', 'department', 'participants_only'], default: 'public' },
  status: { type: String, enum: ['scheduled', 'confirmed', 'rescheduled', 'cancelled', 'completed'], default: 'scheduled', index: true },
  cancellationReason: { type: String, trim: true, default: '' },

  // Reminders configuration
  reminders: { type: [reminderItemSchema], default: [{ minutesBefore: 15, channel: 'both', sent: false }] },

  // Recurrence configuration
  recurrence: {
    pattern: { type: String, enum: ['none', 'daily', 'weekly', 'monthly', 'yearly', 'custom'], default: 'none' },
    interval: { type: Number, default: 1 },
    daysOfWeek: { type: [Number], default: [] }, // 0=Sun..6=Sat
    endDate: { type: String, default: null }, // YYYY-MM-DD
    seriesId: { type: String, default: null, index: true },
    isException: { type: Boolean, default: false },
    originalDate: { type: String, default: null },
  },

  timezone: { type: String, default: 'Asia/Kolkata' },

  // Automated HR integration source reference
  sourceType: {
    type: String,
    enum: [
      'manual',
      'holiday',
      'employee_birthday',
      'employee_anniversary',
      'employee_joining',
      'employee_probation',
      'employee_contract',
      'leave_approved',
      'training',
      'interview',
      'system',
    ],
    default: 'manual',
    index: true,
  },
  sourceId: { type: String, default: null, index: true },
  sourceData: { type: mongoose.Schema.Types.Mixed, default: null },

  // Audit history
  auditHistory: [{
    action: { type: String, required: true },
    actorId: { type: String },
    actorName: { type: String },
    timestamp: { type: Date, default: Date.now },
    details: { type: String },
  }],
}, { timestamps: true })

calendarEventSchema.index({ date: 1, department: 1 })
calendarEventSchema.index({ 'participants.employeeId': 1 })
calendarEventSchema.index({ sourceType: 1, sourceId: 1 })
calendarEventSchema.index({ status: 1, date: 1 })

export const CalendarEvent = mongoose.models.CalendarEvent ?? mongoose.model('CalendarEvent', calendarEventSchema)
export { EVENT_CATEGORIES }
